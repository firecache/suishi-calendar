// 法定节假日与调休安排
// 数据来源：国务院办公厅历年《关于部分节假日安排的通知》（gov.cn 官方原文）
//   - 2024：国办发明电〔2023〕7号
//   - 2025：国办发明电〔2024〕12号（自2025年起全体公民假日增加2天：春节、劳动节各+1天）
//   - 2026：国办发明电〔2025〕7号
// rest(休) = 法定放假休息日（含连休的周末）；work(班) = 调休补班日（原周末调整为工作日）
// 注意：此数据无法用算法推导（国务院每年公布调休方案），必须逐年维护。
// 2027 年安排通常于 2026 年 11 月公布，届时在此表补充。

const DATA = {
  2024: {
    rest: ['1-1', '2-10', '2-11', '2-12', '2-13', '2-14', '2-15', '2-16', '2-17', '4-4', '4-5', '4-6', '5-1', '5-2', '5-3', '5-4', '5-5', '6-8', '6-9', '6-10', '9-15', '9-16', '9-17', '10-1', '10-2', '10-3', '10-4', '10-5', '10-6', '10-7'],
    work: ['2-4', '2-18', '4-7', '4-28', '5-11', '9-14', '9-29', '10-12']
  },
  2025: {
    rest: ['1-1', '1-28', '1-29', '1-30', '1-31', '2-1', '2-2', '2-3', '2-4', '4-4', '4-5', '4-6', '5-1', '5-2', '5-3', '5-4', '5-5', '5-31', '6-1', '6-2', '10-1', '10-2', '10-3', '10-4', '10-5', '10-6', '10-7', '10-8'],
    work: ['1-26', '2-8', '4-27', '9-28', '10-11']
  },
  2026: {
    rest: ['1-1', '1-2', '1-3', '2-15', '2-16', '2-17', '2-18', '2-19', '2-20', '2-21', '2-22', '2-23', '4-4', '4-5', '4-6', '5-1', '5-2', '5-3', '5-4', '5-5', '6-19', '6-20', '6-21', '9-25', '9-26', '9-27', '10-1', '10-2', '10-3', '10-4', '10-5', '10-6', '10-7'],
    work: ['1-4', '2-14', '2-28', '5-9', '9-20', '10-10']
  }
};

// 预编译为扁平 Map，加速查询
const restSet = new Set();
const workSet = new Set();
for (const y in DATA) {
  DATA[y].rest.forEach(k => restSet.add(y + '-' + k));
  DATA[y].work.forEach(k => workSet.add(y + '-' + k));
}

/**
 * 返回某日的假期类型：'rest'（休）、'work'（班）或 null（普通日）
 * @param {number} y 年 @param {number} m 月 @param {number} d 日
 */
export function getHolidayType(y, m, d) {
  const key = y + '-' + m + '-' + d;
  if (restSet.has(key)) return 'rest';
  if (workSet.has(key)) return 'work';
  return null;
}

export default { getHolidayType, DATA };
